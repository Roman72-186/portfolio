// assetUrl.js — единственное место, где записан адрес хранилища ассетов
// 3D-лаборатории (модели, бинарники, текстуры, превью карточек, схемы).
//
// До 01.09.2026 всё это ходило через внешний прокси `https://api.apparchi.ru/?path=`.
// Тот сервер перестал отвечать (TLS-хендшейк отваливается для любого имени, порт 80
// закрыт, машина — чужой VPS у AdminVPS), и лаборатория осталась без единой модели.
// Прокси при этом ничего не закрывал: бакет отдаёт те же файлы по прямой ссылке
// кому угодно и с `Access-Control-Allow-Origin: *`. Поэтому адрес переведён прямо
// на S3 — то же хранилище, откуда лаборатория уже берёт видео уроков.
//
// Раньше эта склейка URL была скопирована в шести файлах-вьюверах плюс две
// константы BASE в каталогах моделей. Теперь адрес один: понадобится закрыть
// модели сессией (свой роут-выдача в приложении) — менять только ASSET_BASE,
// потребителей трогать не надо.
export const ASSET_BASE =
  "https://s3.twcstorage.ru/540d791f-86c02015-75b1-462f-b960-b855e300451a/";

// Абсолютный адрес оставляем как есть: часть контента (видео) уже прописана
// полными ссылками, часть приходит как data:-URL.
function isAbsolute(value) {
  return (
    /^https?:\/\//i.test(value) ||
    value.startsWith("/") ||
    value.startsWith("data:")
  );
}

// Относительный путь внутри бакета -> полный URL.
// Кодируем посегментно, чтобы не съесть разделители каталогов.
export function resolveAssetUrl(value) {
  if (!value) return "";

  const s = String(value);
  if (isAbsolute(s)) return s;

  return ASSET_BASE + s.split("/").map(encodeURIComponent).join("/");
}
