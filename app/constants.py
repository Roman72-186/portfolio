TARIFF_SELF = "Я САМ"
TARIFF_WITH_YOU = "Я С ВАМИ"
TARIFF_CONFIDENT_MAX = "УВЕРЕННЫЙ МАКСИМУМ"

# Что можно назначить сегодня — эти три и попадают в выпадающие списки.
TARIFFS_CURRENT = [TARIFF_SELF, TARIFF_WITH_YOU, TARIFF_CONFIDENT_MAX]

# Отработавшие значения. Не назначаются, но остаются валидными: на них висят
# живые люди и их работы, а фильтры по архиву должны их находить.
TARIFFS_LEGACY = ["МАКСИМУМ", "УВЕРЕННЫЙ"]

# Все значения, которые база считает допустимыми — always UPPER. Порядок:
# сначала действующие, потом отработавшие.
#
# **Проверять принадлежность по `TARIFFS`, а выбор давать из
# `TARIFFS_CURRENT`.** Если валидация сузится до действующих, сохранение
# карточки старого ученика начнёт падать, а фильтр по архиву — пустеть.
TARIFFS = TARIFFS_CURRENT + TARIFFS_LEGACY

def tariff_choices(*assigned: str | None) -> list[str]:
    """Что предлагать в выборе тарифа: действующая линейка плюс уже стоящие старые.

    Владелец 28.09.2026: «те, которые сейчас не задействованы тарифами, те нужно
    скрыть, чтобы их нигде не было видно». Отсюда два правила разом — назначать
    можно только действующие, но собственное значение того, кого правят, в
    списке остаётся. Без второго правила браузер выберет первый пункт, и простое
    сохранение карточки молча переведёт человека с «МАКСИМУМА» на «Я САМ».

    `assigned` — значения, которые нужно сохранить видимыми (тариф ученика,
    тариф ученика плюс тариф работы и т.п.). Пустые игнорируются.
    """
    tail = [
        value for value in dict.fromkeys((a or "").strip() for a in assigned)
        if value and value not in TARIFFS_CURRENT
    ]
    return TARIFFS_CURRENT + tail


def tariffs_for_data(values) -> list[str]:
    """Тарифы для фильтров, таблиц и выгрузок — по фактическим данным.

    Действующая линейка идёт всегда и в своём порядке (фильтр с нулём
    результатов безобиден, а прыгающий состав пунктов — нет), старые значения
    добавляются только когда реально встречаются в этих данных. Так отработавший
    тариф исчезает с экрана сам, как только на нём никого не осталось, и его не
    нужно вычищать из кода отдельной правкой.

    Раньше эти места перечисляли `TARIFFS`, и выгрузка статистики рисовала
    пустые листы «МАКСИМУМ» и «УВЕРЕННЫЙ» в каждом отчёте нового потока.
    """
    present = {(value or "").strip() for value in values}
    legacy = sorted(t for t in present if t and t not in TARIFFS_CURRENT)
    return TARIFFS_CURRENT + legacy


